"""Deterministic sensitive-data classifier.

Two signal classes, combined with confidence weighting:

1. column-NAME heuristics (``email``, ``ssn``, ``salary`` ...)
2. VALUE-pattern matching (regexes over sample values)

The output is a proposal list -- the Classification Agent persists accepted
tags. The LLM is never involved here; it only narrates results later.

All regexes are tuned on SYNTHETIC value formats generated by
simulator/generate_estate.py. Tricky negatives (years, order totals, tracking
numbers) are covered by tests/test_classifier.py.
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field

# ------------------------------------------------------------------ types ---
TAG_EMAIL = "email"
TAG_PHONE = "phone"
TAG_ADDRESS = "address"
TAG_GOV_ID = "gov_id_like"
TAG_SALARY = "salary"
TAG_BANK = "bank_like"
TAG_CUSTOMER_ID = "customer_id"
TAG_EMPLOYEE_ID = "employee_id"
TAG_CREDENTIAL = "credential_like"

LEVEL_FOR_TAG = {
    TAG_EMAIL: "pii",
    TAG_PHONE: "pii",
    TAG_ADDRESS: "pii",
    TAG_GOV_ID: "restricted",
    TAG_SALARY: "confidential",
    TAG_BANK: "restricted",
    TAG_CUSTOMER_ID: "internal",
    TAG_EMPLOYEE_ID: "internal",
    TAG_CREDENTIAL: "credential",
}

NAME_HINTS: dict[str, tuple[float, ...]] = {
    # tag -> (name-hit confidence, name-miss penalty applied elsewhere)
    TAG_EMAIL: (0.9,),
    TAG_PHONE: (0.85,),
    TAG_ADDRESS: (0.8,),
    TAG_GOV_ID: (0.95,),
    TAG_SALARY: (0.9,),
    TAG_BANK: (0.9,),
    TAG_CUSTOMER_ID: (0.75,),
    TAG_EMPLOYEE_ID: (0.75,),
    TAG_CREDENTIAL: (0.95,),
}

_NAME_PATTERNS: dict[str, list[re.Pattern]] = {
    TAG_EMAIL: [re.compile(r"(e[-_]?mail)", re.I)],
    TAG_PHONE: [re.compile(r"(phone|mobile|msisdn|tel)", re.I)],
    TAG_ADDRESS: [re.compile(r"address|street|city_state|postal", re.I)],
    TAG_GOV_ID: [re.compile(r"(ssn|social_?sec|national_?id|gov[_-]?id|tax_?id)", re.I)],
    TAG_SALARY: [re.compile(r"(salary|comp(ensation)?|wage|pay_?(rate|band))", re.I)],
    TAG_BANK: [re.compile(r"(iban|bank_?acct|account_?no|routing_?num)", re.I)],
    TAG_CUSTOMER_ID: [re.compile(r"customer_?id|cust_?no", re.I)],
    TAG_EMPLOYEE_ID: [re.compile(r"employee_?id|emp_?no|staff_?id", re.I)],
    TAG_CREDENTIAL: [re.compile(r"(secret|password|passwd|pwd|token|api_?key|credential|private_?key)", re.I)],
}

_VALUE_PATTERNS: dict[str, list[tuple[re.Pattern, float]]] = {
    # email is UNANCHORED: it must also surface inside free-text fields
    # (e.g. support ticket notes) -- every other pattern is anchored.
    TAG_EMAIL: [
        (re.compile(r"[A-Za-z0-9._%+-]+@[A-Za-z0-9-]+\.[A-Za-z0-9.-]*[A-Za-z]"), 0.95),
    ],
    TAG_PHONE: [
        (re.compile(r"^\+1-\d{3}-\d{3}-\d{4}$"), 0.95),
        (re.compile(r"^\(\d{3}\) \d{3}-\d{4}$"), 0.93),
        (re.compile(r"^\d{3}-\d{3}-\d{4}$"), 0.88),
    ],
    # Street number + name + street-type suffix (+ optional unit).
    TAG_ADDRESS: [
        (re.compile(r"^\d{1,5} [A-Z][a-z]+ (St|Ave|Blvd|Rd|Lane|Way|Court)\.?("
                    r" (Apt|Suite|Unit) \d+[A-Za-z]?)?$"), 0.94),
    ],
    # Clearly-fake government-ID format used by the simulator: 900-NN-NNNN
    # (never a valid real SSN range) plus generic NNN-NN-NNNN.
    TAG_GOV_ID: [
        (re.compile(r"^9\d\d-[0-9]{2}-[0-9]{4}$"), 0.97),
        (re.compile(r"^[0-9]{3}-[0-9]{2}-[0-9]{4}$"), 0.9),
    ],
    # Salary: comma-grouped amount in [25,000 .. ~999,999]; plain ungrouped
    # integers (order totals, ARR figures) deliberately do NOT match, nor do
    # bare years (also blocked by NEGATIVE_GUARDS).
    TAG_SALARY: [(re.compile(r"^(?:[2-9]\d,[0-9]{3}|[1-9][0-9]{2},[0-9]{3})(?:\.[0-9]{2})?$"),
                  0.85)],
    TAG_BANK: [
        (re.compile(r"^DE89\s?\d{4}\s?\d{4}\s?\d{4}\s?\d{4}\s?\d{2}$"), 0.96),   # fake IBAN style
        (re.compile(r"^[0-9]{9,18}$"), 0.7),
    ],
    TAG_CUSTOMER_ID: [(re.compile(r"^CUS-\d{6}$"), 0.97)],
    TAG_EMPLOYEE_ID: [(re.compile(r"^EMP-\d{5}$"), 0.97)],
    # credential-like: long base64ish secrets, key=value pairs, PEM fragments
    TAG_CREDENTIAL: [
        (re.compile(r"^(sk|pk|api)[-_][A-Za-z0-9_-]{16,}$"), 0.97),
        (re.compile(r"^[A-Za-z0-9+/]{32,}={0,2}$"), 0.75),
        (re.compile(r"^-----BEGIN [A-Z ]*PRIVATE KEY-----"), 0.99),
        (re.compile(r"(aws_)?secret_access_key[:=]", re.I), 0.95),
    ],
}

# Values that look numeric but must NOT trigger salary/bank detectors.
NEGATIVE_GUARDS = {
    TAG_SALARY: re.compile(r"^(19|20)\d{2}$"),          # years 1900..2099
    TAG_BANK: re.compile(r"^(19|20)\d{2}$"),
}


@dataclass
class ClassificationProposal:
    tag: str
    level: str
    confidence: float
    source: str            # "name" | "value" | "name+value"
    detector: str          # which detector produced it
    matched_samples: list[str] = field(default_factory=list)

    def as_dict(self) -> dict:
        return {"tag": self.tag, "level": self.level, "confidence": round(self.confidence, 3),
                "source": self.source, "detector": self.detector,
                "matched_samples": self.matched_samples[:3]}


def classify_column(name: str, data_type: str, samples: list[str]) -> list[ClassificationProposal]:
    """Classify one column from its name and sample values. Deterministic."""
    proposals: dict[str, ClassificationProposal] = {}

    for tag, pats in _NAME_PATTERNS.items():
        if any(p.search(name or "") for p in pats):
            conf = NAME_HINTS[tag][0]
            proposals[tag] = ClassificationProposal(tag, LEVEL_FOR_TAG[tag], conf, "name",
                                                    f"name:{tag}")

    cleaned = [str(s) for s in (samples or []) if s is not None and str(s).strip() != ""]
    for tag, entries in _VALUE_PATTERNS.items():
        hits = 0
        conf = 0.0
        matched: list[str] = []
        for sval in cleaned:
            if NEGATIVE_GUARDS.get(tag) and NEGATIVE_GUARDS[tag].match(sval):
                continue
            for rx, c in entries:
                if rx.search(sval):
                    hits += 1
                    conf = max(conf, c)
                    matched.append(sval)
                    break
        need = max(1, min(len(cleaned), 2))
        if hits >= need:
            vconf = conf * min(1.0, 0.6 + 0.4 * hits / max(len(cleaned), 1))
            existing = proposals.get(tag)
            if existing:
                existing.confidence = min(0.99, max(existing.confidence, vconf) + 0.05)
                existing.source = "name+value"
                existing.matched_samples = matched
            else:
                proposals[tag] = ClassificationProposal(tag, LEVEL_FOR_TAG[tag], round(vconf, 3),
                                                        "value", f"value:{tag}", matched)
    ranked = sorted(proposals.values(), key=lambda p: (-p.confidence, p.tag))
    return ranked


def dataset_level(columns_with_tags: list[list[str]], intended_level: str | None = None) -> str:
    """Roll column tags up to a dataset sensitivity level."""
    levels = {LEVEL_FOR_TAG[t] for cols in columns_with_tags for t in cols}
    order = ["public", "internal", "confidential", "restricted"]
    rank = {lv: i for i, lv in enumerate(order)}
    best = "internal"
    for lv in levels:
        if rank.get(lv, 1) > rank.get(best, 1):
            best = lv
    return best


def classification_coverage(datasets: list[dict], classified_keys: set[tuple[int, int]]) -> float:
    """classified_keys holds (dataset_idx, col_idx) of classified columns."""
    total = sum(len(d["columns"]) for d in datasets)
    if total == 0:
        return 1.0
    return len(classified_keys & {(di, ci) for di, d in enumerate(datasets)
                                  for ci in range(len(d["columns"]))}) / total
